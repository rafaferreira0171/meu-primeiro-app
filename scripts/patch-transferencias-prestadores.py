from pathlib import Path

p = Path('src/main.jsx')
s = p.read_text()
start = s.find('function transferOptions(')
end = s.find('function Budget(', start)
if start < 0 or end < 0:
    raise SystemExit('Transfer component block not found')

new = r'''function transferOptions(data,month){
  const f=data.fluxo.find(x=>x.month===month)||{}
  const fixed=FLUXO_FIELDS.filter(([key])=>Object.prototype.hasOwnProperty.call(f,key)).map(([key,label])=>({id:`fluxo:${key}`,label,value:Number(f[key]||0)}))
  const custom=data.despesas.filter(x=>x.month===month&&x.ativo!==false).map(x=>({id:`despesa:${x.series_id||x.id}`,label:x.nome,value:Number(x.valor||0)}))
  const prestadoresTotal=data.prestadores.filter(x=>x.month===month&&x.ativo!==false).reduce((s,p)=>{const bruto=totalPrestador(p);const pct=Math.min(100,Math.max(0,Number(p.fluxo_percent??100)));return s+bruto*pct/100},0)
  const prestadores=prestadoresTotal>0?[{id:'fluxo:prestadores',label:'Prestadores de Serviço',value:prestadoresTotal}]:[]
  return [...fixed,...prestadores,...custom].filter(x=>x.value>0)
}
function transferValue(t,data,month){
  const options=transferOptions(data,month),refs=Array.isArray(t.items)?t.items:[]
  if(!refs.length)return Number(t.valor||0)
  return refs.reduce((s,id)=>s+(options.find(o=>o.id===id)?.value||0),0)
}
function Transferencias({data,save,month,setMonth}){
  const rows=data.transferencias.filter(x=>x.month===month&&x.ativo!==false),options=transferOptions(data,month),[editing,setEditing]=useState(null)
  const open=t=>setEditing(t?{...t,items:[...(Array.isArray(t.items)?t.items:[])]}:{id:null,nome:'',items:[]})
  const close=()=>setEditing(null)
  const toggle=id=>setEditing(x=>({...x,items:x.items.includes(id)?x.items.filter(v=>v!==id):[...x.items,id]}))
  const total=editing?.items.reduce((s,id)=>s+(options.find(o=>o.id===id)?.value||0),0)||0
  const saveTransfer=()=>{
    if(!editing?.nome?.trim()||!editing.items.length)return
    const value=total
    if(editing.id){
      save({...data,transferencias:data.transferencias.map(x=>x.id===editing.id?{...x,nome:editing.nome.trim(),items:editing.items,valor:value}:x)})
    }else{
      const id=crypto.randomUUID()
      save({...data,transferencias:[...data.transferencias,{id,series_id:id,month,nome:editing.nome.trim(),items:editing.items,valor:value,ativo:true}]})
    }
    close()
  }
  const remove=id=>save({...data,transferencias:data.transferencias.map(x=>x.id===id?{...x,ativo:false}:x)})
  return <><div className="toolbar"><MonthSelect month={month} setMonth={setMonth} months={data.transferencias.map(x=>x.month)}/><button className="primary" onClick={()=>open()}>+ Transferência</button></div><Section title="Transferências"><div className="note">Selecione as despesas do Fluxo que compõem cada transferência. O valor é calculado automaticamente pela soma das despesas selecionadas.</div>{rows.map(t=>{const value=transferValue(t,data,month);return <div className="transfer-card" key={t.id}><div><strong>{t.nome}</strong><span>{(Array.isArray(t.items)?t.items:[]).length} despesa(s) vinculada(s)</span></div><b>{BRL(value)}</b><button className="ghost" onClick={()=>open(t)}>Editar</button><button className="ghost" onClick={()=>remove(t.id)}>Encerrar</button></div>})}{!rows.length&&<div className="empty">Nenhuma transferência neste mês.</div>}</Section>{editing&&<Modal title={editing.id?'Editar transferência':'Nova transferência'} onClose={close} onSave={saveTransfer} saveLabel="Salvar"><FormField label="Nome da transferência"><input autoFocus value={editing.nome} onChange={e=>setEditing(x=>({...x,nome:e.target.value}))} placeholder="Ex.: Cartão / Conta conjunta"/></FormField><div className="selection-total"><span>Valor calculado</span><strong>{BRL(total)}</strong></div><div className="expense-picker">{options.map(o=><label key={o.id} className="expense-option"><input type="checkbox" checked={editing.items.includes(o.id)} onChange={()=>toggle(o.id)}/><span>{o.label}</span><b>{BRL(o.value)}</b></label>)}</div>{!options.length&&<div className="empty">Nenhuma despesa com valor disponível no Fluxo deste mês.</div>}</Modal>}</>
}
'''
